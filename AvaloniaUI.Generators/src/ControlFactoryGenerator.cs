namespace Lytec.AvaloniaUI.Generators;

[Generator]
public sealed class ControlFactoryGenerator : IIncrementalGenerator
{
    private const string GenerateAttributeName =
        "Lytec.AvaloniaUI.Generators.GenerateControlFactoriesAttribute";
    private const string IncludeAttributeName =
        "Lytec.AvaloniaUI.Generators.IncludeControlFactoryAttribute";
    private const string ControlTypeName = "Avalonia.Controls.Control";
    private const string ViewBaseTypeName = "Avalonia.Markup.Declarative.ViewBase";
    private const string ContentAttributeName = "Avalonia.Metadata.ContentAttribute";

    private static readonly DiagnosticDescriptor TargetMustBePartial = new(
        "LYAVGEN001",
        "Control factory target must be partial",
        "Type '{0}' and all of its containing types must be partial",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor TargetMustDeriveFromViewBase = new(
        "LYAVGEN002",
        "Invalid control factory target",
        "Type '{0}' must derive from Avalonia.Markup.Declarative.ViewBase",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor InvalidIncludedControl = new(
        "LYAVGEN003",
        "Invalid included control",
        "Type '{0}' must be an accessible, non-abstract Control with a public zero-argument constructor",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor InvalidAlias = new(
        "LYAVGEN004",
        "Invalid control factory alias",
        "Alias '{0}' for control '{1}' is not a valid C# identifier",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor InvalidPrimaryProperty = new(
        "LYAVGEN005",
        "Invalid primary control property",
        "Primary property '{0}' on control '{1}' is not supported by the current Declarative-style factory rules",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor FactoryNameConflict = new(
        "LYAVGEN006",
        "Control factory name conflict",
        "Factory name '{0}' is used by both '{1}' and '{2}'; configure an Alias to resolve the conflict",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor ExistingMemberConflictDiagnostic = new(
        "LYAVGEN007",
        "Control factory conflicts with an existing member",
        "Factory '{0}' for control '{1}' conflicts with existing member '{2}'; configure an Alias or rename the member",
        "Usage",
        DiagnosticSeverity.Error,
        true);

    private static readonly DiagnosticDescriptor ThirdPartyPrimaryPropertyNotFound = new(
        "LYAVGEN008",
        "No primary property inferred for included control",
        "No primary property could be inferred for included control '{0}'; only the parameterless factory will be generated",
        "Usage",
        DiagnosticSeverity.Warning,
        true);

